"""Release helpers used by .github/workflows/release.yml and ci.yml (ARCHITECTURE.md §7).

python tools/release.py stamp <tag>        # write version into __init__.py + version_info.txt
python tools/release.py version-info        # write version_info.txt for the current version
python tools/release.py sums <file>...      # write SHA256SUMS.txt next to the first file
python tools/release.py meta <tag>          # print version=/prerelease= lines for $GITHUB_OUTPUT
"""

from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INIT = ROOT / "src" / "mousemusic" / "__init__.py"
VERSION_INFO = ROOT / "packaging" / "version_info.txt"
TAG_RE = re.compile(r"^v(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z][0-9A-Za-z.-]*))?$")

VERSION_INFO_TEMPLATE = """# UTF-8 — generated by tools/release.py; do not edit by hand.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={nums},
    prodvers={nums},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
        StringStruct('CompanyName', 'MouseMusic'),
        StringStruct('FileDescription', 'MouseMusic'),
        StringStruct('FileVersion', '{version}'),
        StringStruct('InternalName', 'MouseMusic'),
        StringStruct('LegalCopyright', 'MIT License'),
        StringStruct('OriginalFilename', 'MouseMusic.exe'),
        StringStruct('ProductName', 'MouseMusic'),
        StringStruct('ProductVersion', '{version}')
      ])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def parse_tag(tag: str) -> tuple[str, bool, tuple[int, int, int, int]]:
    """``v1.2.3[-rc1]`` → (``1.2.3[-rc1]``, prerelease?, numeric 4-tuple for VERSIONINFO)."""
    m = TAG_RE.match(tag.strip())
    if not m:
        raise ValueError(f"not a release tag (want vX.Y.Z or vX.Y.Z-suffix): {tag!r}")
    major, minor, patch, pre = m.groups()
    version = f"{major}.{minor}.{patch}" + (f"-{pre}" if pre else "")
    return version, pre is not None, (int(major), int(minor), int(patch), 0)


def current_version(init: Path = INIT) -> str:
    m = re.search(r'^__version__ = "([^"]+)"', init.read_text(encoding="utf-8"), re.M)
    if not m:
        raise ValueError(f"no __version__ in {init}")
    return m.group(1)


def write_version_info(version: str, path: Path = VERSION_INFO) -> None:
    nums = parse_tag(f"v{version}")[2]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(VERSION_INFO_TEMPLATE.format(nums=nums, version=version), encoding="utf-8")


def stamp(tag: str, init: Path = INIT, info: Path = VERSION_INFO) -> str:
    version = parse_tag(tag)[0]
    text = init.read_text(encoding="utf-8")
    new, n = re.subn(r'^__version__ = "[^"]*"', f'__version__ = "{version}"', text, flags=re.M)
    if n != 1:
        raise ValueError(f"no __version__ line in {init}")
    init.write_text(new, encoding="utf-8")
    write_version_info(version, info)
    return version


def sha256sums(files: list[Path], out: Path | None = None) -> Path:
    out = out or files[0].parent / "SHA256SUMS.txt"
    lines = []
    for f in files:
        digest = hashlib.sha256(f.read_bytes()).hexdigest()
        lines.append(f"{digest}  {f.name}\n")
    out.write_text("".join(lines), encoding="utf-8", newline="\n")
    return out


def main(argv: list[str]) -> int:
    if not argv:
        print(__doc__)
        return 2
    cmd, args = argv[0], argv[1:]
    if cmd == "stamp":
        print(stamp(args[0]))
    elif cmd == "version-info":
        write_version_info(current_version())
    elif cmd == "sums":
        print(sha256sums([Path(a) for a in args]).read_text(encoding="utf-8"), end="")
    elif cmd == "meta":
        version, pre, _ = parse_tag(args[0])
        print(f"version={version}\nprerelease={'true' if pre else 'false'}")
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
